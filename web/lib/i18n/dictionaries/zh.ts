/**
 * The shape every locale must satisfy. Derived from `zh`, so a key added there is required
 * everywhere else. Recursive so nested sections (`settings.nav`) keep their structure while
 * widening every leaf from its literal type to `string`.
 */
export type Dictionary = Translated<typeof zh>;

type Translated<T> = {
  [K in keyof T]: T[K] extends string ? string : Translated<T[K]>;
};
